"""Computes WCAG contrast for the palette and derived tokens. Writes docs/contrast.md and src/styles/tokens.css."""
P, B, L, V, I = "#FFFFFA", "#6294FF", "#A979FA", "#725DFF", "#201E2D"
def lin(c):
    c /= 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
def lum(h):
    r, g, b = (int(h[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
def cr(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)
def mix(a, b, t):  # t is the share of b
    f = lambda h: [int(h[i:i + 2], 16) for i in (1, 3, 5)]
    return "#%02X%02X%02X" % tuple(round(x + (y - x) * t) for x, y in zip(f(a), f(b)))
strong, t = V, 0
while cr(strong, P) < 4.6:  # darken the violet toward ink until small text passes
    t += 0.02; strong = mix(V, I, t)
d = dict(muted_l=mix(P, I, .72), muted_d=mix(I, P, .72), surf_d=mix(I, P, .06),
         line_l=mix(P, I, .55), line_d=mix(I, P, .45), strong=strong)
pairs = [("Ink on Paper", I, P), ("Violet on Paper", V, P), ("Lilac on Paper", L, P), ("Blue on Paper", B, P),
         ("Paper on Violet", P, V), ("Ink on Blue", I, B), ("Ink on Lilac", I, L), ("Ink on Violet", I, V),
         ("Lilac on Ink", L, I), ("Blue on Ink", B, I), ("Violet on Ink", V, I),
         ("Strong violet on Paper (derived)", d["strong"], P), ("Muted text on Paper (derived)", d["muted_l"], P),
         ("Muted text on Ink (derived)", d["muted_d"], I), ("Input border on Paper (derived)", d["line_l"], P),
         ("Input border on Ink (derived)", d["line_d"], I)]
rows = "\n".join(f"| {n} | `{a}` on `{b}` | {cr(a, b):.2f} |" for n, a, b in pairs)
open("docs/contrast.md", "w").write("# Contrast ratios\n\nComputed by scripts/contrast.py with the WCAG formula.\n\n| Pair | Colours | Ratio |\n| --- | --- | --- |\n" + rows + "\n")
open("src/styles/tokens.css", "w").write(f"""/* Generated by scripts/contrast.py. Palette is fixed (D-08). Light is the default (D-07). */
:root {{
  --paper: {P}; --blue: {B}; --lilac: {L}; --violet: {V}; --ink: {I};
  --bg: {P}; --surface: {P}; --text: {I}; --text-muted: {d['muted_l']};
  --accent: {V}; --accent-strong: {d['strong']}; --border: {d['line_l']}; --focus: {V};
  --on-blue: {I}; --on-lilac: {I};
}}
/* Dark is a toggle only until Q-13 is answered. It does not follow the system setting. */
:root[data-theme="dark"] {{
  --bg: {I}; --surface: {d['surf_d']}; --text: {P}; --text-muted: {d['muted_d']};
  --accent: {L}; --accent-strong: {B}; --border: {d['line_d']}; --focus: {L};
}}
""")
print(rows)
